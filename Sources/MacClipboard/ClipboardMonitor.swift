import Foundation
import AppKit

@MainActor
public protocol ClipboardMonitorDelegate: AnyObject {
    func clipboardDidCapture(item: ClipItem)
}

@MainActor
public final class ClipboardMonitor {
    public weak var delegate: ClipboardMonitorDelegate?
    
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    public var isPaused: Bool = false
    public var isPerformingInternalPaste: Bool = false
    
    // Concealed pasteboard types to ignore (passwords, secrets)
    private let concealedTypeNames: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.dstoecker.xfeed.password"
    ]
    
    public init() {
        self.lastChangeCount = pasteboard.changeCount
    }
    
    public func start() {
        guard timer == nil else { return }
        self.lastChangeCount = pasteboard.changeCount
        
        timer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.checkForChanges()
            }
        }
        RunLoop.main.add(timer!, forMode: .common)
    }
    
    public func stop() {
        timer?.invalidate()
        timer = nil
    }
    
    public func updateLastChangeCount() {
        self.lastChangeCount = pasteboard.changeCount
    }
    
    private func checkForChanges() {
        guard !isPaused, !isPerformingInternalPaste else { return }
        let currentChangeCount = pasteboard.changeCount
        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount
        
        // Check for password / secret exclusion
        if let types = pasteboard.types {
            for type in types {
                if concealedTypeNames.contains(type.rawValue) {
                    return
                }
            }
        }
        
        let frontApp = NSWorkspace.shared.frontmostApplication
        let appName = frontApp?.localizedName
        let bundleId = frontApp?.bundleIdentifier
        
        // 1. Check for images first if available
        if let image = readImageFromPasteboard() {
            if let saved = StorageManager.shared.saveImage(image) {
                let item = ClipItem(
                    type: .image,
                    imageFileName: saved.fileName,
                    imageWidth: saved.width,
                    imageHeight: saved.height,
                    sourceAppName: appName,
                    sourceAppBundleId: bundleId
                )
                delegate?.clipboardDidCapture(item: item)
                return
            }
        }
        
        // 2. Check for string
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\\ ", with: " ")
            let imageExts: Set<String> = ["png", "jpg", "jpeg", "heic", "tiff", "gif", "webp"]
            if trimmed.hasPrefix("/"), imageExts.contains(URL(fileURLWithPath: trimmed).pathExtension.lowercased()) {
                if FileManager.default.fileExists(atPath: trimmed), let image = NSImage(contentsOfFile: trimmed) {
                    if let saved = StorageManager.shared.saveImage(image) {
                        let item = ClipItem(
                            type: .image,
                            imageFileName: saved.fileName,
                            imageWidth: saved.width,
                            imageHeight: saved.height,
                            sourceAppName: appName ?? "Screenshot",
                            sourceAppBundleId: bundleId
                        )
                        delegate?.clipboardDidCapture(item: item)
                        return
                    }
                }
            }
            
            let clipType = categorize(string: string)
            let item = ClipItem(
                type: clipType,
                textContent: string,
                sourceAppName: appName,
                sourceAppBundleId: bundleId
            )
            delegate?.clipboardDidCapture(item: item)
        }
    }
    
    private func readImageFromPasteboard() -> NSImage? {
        // 1. Try reading directly via NSImage pasteboard initializer
        if let image = NSImage(pasteboard: pasteboard) {
            return image
        }
        
        // 2. Try reading NSImage objects
        if let objects = pasteboard.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage], let first = objects.first {
            return first
        }
        
        // 3. Try reading image file URLs (e.g. copied screenshot or image file in Finder)
        let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "tiff", "gif", "webp", "bmp", "ico"]
        if let fileURLs = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL] {
            for url in fileURLs {
                if imageExtensions.contains(url.pathExtension.lowercased()) {
                    if let image = NSImage(contentsOf: url) {
                        return image
                    }
                }
            }
        }
        
        // 4. Try raw data types
        if let data = pasteboard.data(forType: .png), let image = NSImage(data: data) {
            return image
        }
        if let data = pasteboard.data(forType: .tiff), let image = NSImage(data: data) {
            return image
        }
        
        return nil
    }
    
    private func categorize(string: String) -> ClipType {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        
        // Hex color check: #fff, #ffffff, #ffffffff
        if trimmed.range(of: "^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$", options: .regularExpression) != nil {
            return .color
        }
        
        // URL check
        if trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://") || trimmed.hasPrefix("ftp://") {
            if let url = URL(string: trimmed), url.host != nil {
                return .url
            }
        }
        
        // Code snippet check
        let codeIndicators = [
            "func ", "def ", "class ", "import ", "const ", "let ", "var ",
            "return ", "public ", "private ", "struct ", "interface ",
            "=>", "();", "{\n", "\t", "console.log", "print("
        ]
        let lines = trimmed.components(separatedBy: .newlines)
        if lines.count > 2 || trimmed.contains("{") && trimmed.contains("}") {
            var indicatorMatches = 0
            for indicator in codeIndicators {
                if trimmed.contains(indicator) {
                    indicatorMatches += 1
                }
            }
            if indicatorMatches >= 2 {
                return .code
            }
        }
        
        return .text
    }
}
